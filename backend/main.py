"""
main.py – StreamInsight FastAPI Backend
----------------------------------------
Serves processed analytics data computed by the PySpark ETL job.

Data flow:
  CSV (data/) → PySpark ETL (spark/spark_etl.py) → JSON (spark/output/) → FastAPI → Dashboard

Run:
  uvicorn backend.main:app --reload --port 8000
"""

