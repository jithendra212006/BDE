# ── Content Performance ───────────────────────────────────────────────────────
@app.get("/api/content", tags=["Analytics"])
def get_content(
    genre:   Optional[str] = Query(default=None),
    search:  Optional[str] = Query(default=None),
    sort_by: str            = Query(default="totalViews",
                                    regex="^(totalViews|completionRate|rating|totalWatchHours)$"),
    limit:   int            = Query(default=50, ge=1, le=100),
    offset:  int            = Query(default=0,  ge=0),
):
    """
    Full content catalog with views, watch hours, completion rates, and ratings.
    Supports genre filtering, text search, and sorting.
    """
    data: List[Dict] = load_json("content.json")
    if genre:
        data = [d for d in data if d["genre"].lower() == genre.lower()]
    if search:
        q = search.lower()
        data = [d for d in data if q in d["title"].lower() or q in d["genre"].lower()]
    data.sort(key=lambda x: x.get(sort_by, 0), reverse=True)
    return {
        "total":  len(data),
        "offset": offset,
        "limit":  limit,
        "items":  data[offset: offset + limit],
    }

@app.get("/api/content/trending", tags=["Analytics"])
def get_trending(limit: int = Query(default=5, ge=1, le=20)):
    """Top trending titles by view count."""
    data: List[Dict] = load_json("content.json")
    trending = [d for d in data if d.get("isTrending")]
    return trending[:limit]

