# ── Watch Time Time-Series ────────────────────────────────────────────────────
@app.get("/api/watch-time", tags=["Analytics"])
def get_watch_time(
    range: str = Query(default="30d", regex="^(7d|30d|90d|all)$",
                       description="Date range: 7d | 30d | 90d | all")
):
    """Daily watch time series, filterable by date range."""
    all_data: List[Dict] = load_json("watch_time.json")
    all_data.sort(key=lambda x: x["date"])
    limits = {"7d": 7, "30d": 30, "90d": 90, "all": len(all_data)}
    n = limits[range]
    return all_data[-n:]

