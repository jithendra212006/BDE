# ── Paths ─────────────────────────────────────────────────────────────────────
ROOT        = Path(__file__).resolve().parent.parent
OUTPUT_DIR  = ROOT / "spark" / "output"
CSV_PATH    = ROOT / "data" / "ott_viewing_data.csv"
ETL_SCRIPT  = ROOT / "spark" / "spark_etl.py"

# ── App ───────────────────────────────────────────────────────────────────────
app = FastAPI(
    title="StreamInsight Analytics API",
    description=(
        "REST API serving processed OTT analytics data. "
        "Data is produced by the PySpark ETL job (spark/spark_etl.py) and "
        "stored as JSON in spark/output/."
    ),
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:3000", "http://127.0.0.1:3000"],
    allow_methods=["*"],
    allow_headers=["*"],
)

# ── Data loader ───────────────────────────────────────────────────────────────
def load_json(filename: str) -> Any:
    path = OUTPUT_DIR / filename
    if not path.exists():
        raise HTTPException(
            status_code=503,
            detail=(
                f"Analytics data file '{filename}' not found. "
                "Run the PySpark ETL job first: python spark/spark_etl.py"
            ),
        )
    with open(path, encoding="utf-8") as f:
        return json.load(f)

def data_ready() -> bool:
    return (OUTPUT_DIR / "kpi.json").exists()

# ── Health / status ───────────────────────────────────────────────────────────
@app.get("/", tags=["Health"])
def root():
    return {
        "service": "StreamInsight Analytics API",
        "version": "1.0.0",
        "status":  "running",
        "data_ready": data_ready(),
        "docs": "/docs",
    }

@app.get("/health", tags=["Health"])
def health():
    ready = data_ready()
    return {
        "status": "healthy" if ready else "degraded",
        "pipeline_output_ready": ready,
        "csv_present": CSV_PATH.exists(),
        "output_dir":  str(OUTPUT_DIR),
    }

@app.get("/api/pipeline/status", tags=["Pipeline"])
def pipeline_status():
    """Return which output files have been generated by the Spark ETL job."""
    expected = [
        "kpi.json", "watch_time.json", "genres.json", "peak_hours.json",
        "devices.json", "countries.json", "content.json",
        "subscriptions.json", "retention.json",
    ]
    files = {f: (OUTPUT_DIR / f).exists() for f in expected}
    ready = all(files.values())
    return {"ready": ready, "files": files}

